/**
 * Authored NCE lesson content, keyed by canonical lesson id (e.g. "CH-05-L03").
 *
 * The library renders structure from `curriculum.ts` and looks up authored
 * content here. A lesson without a record renders as "Content in production",
 * so content can be imported one batch at a time with no page changes.
 *
 * Each batch file is generated by `scripts/import-nce-batch.ts` from the
 * authored markdown batch — edit the markdown and re-run the importer rather
 * than hand-editing a batch file, then register it below.
 */
export const nceLessonContent: Record<string, NceLessonContent> = {
  ...or01LessonContent,
  ...or02LessonContent,
  ...po01LessonContent,
  ...po02LessonContent,
  ...po03LessonContent,
  ...po04LessonContent,
  ...po05LessonContent,
  ...po06LessonContent,
  ...ch01LessonContent,
  ...ch02LessonContent,
  ...ch03LessonContent,
  ...ch04LessonContent,

};

export const getNceLessonContent = (lessonId: string): NceLessonContent | undefined =>
  nceLessonContent[lessonId];

export const isNceLessonPublished = (lessonId: string): boolean => lessonId in nceLessonContent;

export const publishedNceLessonIds = (): string[] => Object.keys(nceLessonContent);
